import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { redisCommand as execute } from './_idRedis.mjs';
import { membershipEnrollmentKey } from '../api/_membershipConsumption.js';
import { reconcilePaidEnrollment } from '../api/_membershipPaidEnrollment.js';
let n = 0; const check = x => { assert.ok(x); n++; };
const reject = async fn => { await assert.rejects(fn); n++; };
await execute(['FLUSHDB']);
const owner = 'syntheticEnrollment', sub = 'sub_test', key = membershipEnrollmentKey(owner);
const active = 'membership:launch-v2:active:' + createHash('sha256').update(owner).digest('hex');
await reject(() => reconcilePaidEnrollment(execute, owner, sub));
check(await execute(['GET', key]) === null);
await execute(['SET', 'membership:launch-v2:legacy_fence', '1']);
const record = { version: 'launch-v2', owner, verified: true, plan: 'free', freeThrough: 1800000000,
  capabilities: { bulkGrade: false }, preserved: 'historical provenance',
  historical: { large: 9007199254740990, empty: [] } };
await execute(['SET', key, JSON.stringify(record)]);
await reject(() => reconcilePaidEnrollment(execute, owner, sub));
check(await execute(['GET', key]) === JSON.stringify(record));
await execute(['SET', active, JSON.stringify({ version: 'launch-v2', owner, subscription: sub })]);
await execute(['SET', `scans:${owner}:id_paid_left`, '101']);
await Promise.all(Array.from({ length: 10 }, () => reconcilePaidEnrollment(execute, owner, sub)));
let current = JSON.parse(await execute(['GET', key]));
check(current.plan === 'paid' && current.subscription === sub);
check(current.freeThrough === record.freeThrough && current.capabilities.bulkGrade === false && current.preserved === record.preserved);
check(current.historical.large === record.historical.large);
check(Array.isArray(current.historical.empty) && current.historical.empty.length === 0);
check(await execute(['GET', `scans:${owner}:id_paid_left`]) === '101');
const raw = await execute(['GET', key]); await reconcilePaidEnrollment(execute, owner, sub);
check(await execute(['GET', key]) === raw);
await reject(() => reconcilePaidEnrollment(execute, owner, 'sub_other'));
check(await execute(['GET', key]) === raw);
delete current.freeThrough;
await execute(['SET', key, JSON.stringify(current)]);
const paidRaw = await execute(['GET', key]);
await reconcilePaidEnrollment(execute, owner, sub);
check(await execute(['GET', key]) === paidRaw);
check(!Object.hasOwn(JSON.parse(await execute(['GET', key])), 'freeThrough'));
console.log(`membership-paid-enrollment: ${n} passed, 0 failed`);
process.exit(0);

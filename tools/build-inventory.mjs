import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
let html=await readFile(new URL('index.html',root),'utf8');
for(const name of ['inventory-edits','inventory-details','inventory-conflicts','collection-drafts']){
 const source=name==='inventory-edits'
  ?'// Generated by tools/build-inventory.mjs\n(()=>{\n'+(await readFile(new URL('api/_inventoryEdits.js',root),'utf8')).replace(/^export /gm,'')+'\nwindow.CardResellInventoryEdits={editInventory,mergeInventoryEdit,mergeInventory,inventoryConflicts,resolveInventoryEdit,inventoryNotDeleted};\n})();\n'
  :await readFile(new URL('js/'+name+'.js',root),'utf8');
 const path='js/'+name+'.'+createHash('sha256').update(source).digest('hex').slice(0,8)+'.js';
 const pattern=new RegExp('js/'+name+'\\.[a-f0-9]{8}\\.js','g');
 if(pattern.test(html))html=html.replace(pattern,path);
 else if(name==='inventory-edits')html=html.replace(/(<script defer src="\/js\/core\.[a-f0-9]{8}\.js"><\/script>)/,`<script defer src="/${path}"></script>\n$1`);
 else html=html.replace(/(<script defer src="\/js\/collection-drafts\.[a-f0-9]{8}\.js"><\/script>)/,`<script defer src="/${path}"></script>\n$1`);
 if(!html.includes(path))throw Error('Missing script anchor for '+name);
 await writeFile(new URL(path,root),source);console.log(path);
}
await writeFile(new URL('index.html',root),html);

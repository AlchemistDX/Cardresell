import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('js/bulk-match-review.js', root));
const path = `js/bulk-match-review.${createHash('sha256').update(source).digest('hex').slice(0,8)}.js`;
let html = await readFile(new URL('index.html', root), 'utf8');
const pattern = /js\/bulk-match-review\.[a-f0-9]{8}\.js/g;
if ([...html.matchAll(pattern)].length > 1) throw Error('Expected one bulk match review asset');
html = pattern.test(html) ? html.replace(pattern,path) : html.replace(/(<script defer src="\/js\/ui\.[a-f0-9]{8}\.js"><\/script>)/,`$1\n<script defer src="/${path}"></script>`);
if (!html.includes(path)) throw Error('Could not attach bulk match review asset');
await writeFile(new URL(path, root), source);
await writeFile(new URL('index.html', root), html);
console.log(path);

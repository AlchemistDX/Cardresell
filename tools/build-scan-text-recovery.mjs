import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),source=await readFile(new URL('js/scan-text-recovery.js',root));
const path='js/scan-text-recovery.'+createHash('sha256').update(source).digest('hex').slice(0,8)+'.js';
let html=await readFile(new URL('index.html',root),'utf8');
const pattern=/js\/scan-text-recovery\.[a-f0-9]{8}\.js/g;
if([...html.matchAll(pattern)].length>1)throw Error('Expected one text recovery asset');
html=pattern.test(html)?html.replace(pattern,path):html.replace(/(<script defer src="\/js\/scan-request\.[a-f0-9]{8}\.js"><\/script>)/,`$1\n<script defer src="/${path}"></script>`);
if(!html.includes(path))throw Error('Could not attach text recovery');
await writeFile(new URL(path,root),source);await writeFile(new URL('index.html',root),html);console.log(path);

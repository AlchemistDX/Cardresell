import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const src=await readFile(new URL('api/_saleCorrections.js',root),'utf8');
const code='// Generated by tools/build-sale-corrections.mjs\n(()=>{\n'+src.replace(/^export /gm,'')+'\nwindow.CardResellSaleCorrections={correctSale,mergeSales,mergeSaleCorrection,resolveSaleCorrection};\n})();\n';
const path='js/sale-corrections.'+createHash('sha256').update(code).digest('hex').slice(0,8)+'.js';
let html=await readFile(new URL('index.html',root),'utf8');
const pattern=/js\/sale-corrections\.[a-f0-9]{8}\.js/g;
if(pattern.test(html))html=html.replace(pattern,path);
else html=html.replace(/(<script defer src="\/js\/core\.[a-f0-9]{8}\.js"><\/script>)/,`<script defer src="/${path}"></script>\n$1`);
await writeFile(new URL(path,root),code);await writeFile(new URL('index.html',root),html);console.log(path);
